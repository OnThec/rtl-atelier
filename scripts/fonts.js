import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { fontFormatForExtension, parseFontFilename } from "../src/core/font-names.js";

// Re-exported so existing consumers (tests) keep a single import surface.
export { parseFontFilename };

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const FONT_EXT_FORMAT = {
  ".woff2": "woff2",
  ".woff": "woff",
  ".ttf": "truetype",
  ".otf": "opentype",
};

const WEIGHT_MAP = {
  thin: 100,
  hairline: 100,
  extralight: 200,
  ultralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  book: 400,
  medium: 500,
  semibold: 600,
  demibold: 600,
  bold: 700,
  extrabold: 800,
  ultrabold: 800,
  black: 900,
  heavy: 900,
};

const FACE_RE = /^(.+?)[-_](thin|hairline|extralight|ultralight|light|regular|normal|book|medium|semibold|demibold|bold|extrabold|ultrabold|black|heavy)$/i;

function formatForFile(file) {
  const ext = file.slice(file.lastIndexOf(".")).toLowerCase();
  return fontFormatForExtension(ext) || "truetype";
}

export function collectFontFamilies(fileNames, manifest = null) {
  const map = new Map();
  const ensure = (family) => {
    if (!map.has(family)) map.set(family, { family, faces: [] });
    return map.get(family);
  };

  if (Array.isArray(manifest)) {
    for (const entry of manifest) {
      if (!entry || typeof entry.family !== "string" || !Array.isArray(entry.faces)) continue;
      const group = ensure(entry.family);
      for (const face of entry.faces) {
        if (!face || typeof face.file !== "string" || !fileNames.includes(face.file)) continue;
        group.faces.push({ file: face.file, weight: Number(face.weight) || 400 });
      }
    }
  } else {
    for (const file of fileNames) {
      const parsed = parseFontFilename(file);
      if (!parsed) continue;
      ensure(parsed.family).faces.push({ file, weight: parsed.weight });
    }
  }

  const families = [...map.values()].filter((group) => group.faces.length > 0);
  for (const group of families) {
    group.faces.sort((a, b) => a.weight - b.weight);
  }
  families.sort((a, b) => a.family.localeCompare(b.family));
  return families;
}

function escapeCssString(value) {
  return String(value).replace(/["\\]/g, (ch) => `\\${ch}`);
}

export function renderFontFaceCss(families, urlFor) {
  const blocks = [];
  for (const group of families) {
    for (const face of group.faces) {
      const format = formatForFile(face.file);
      blocks.push(
        `@font-face {\n` +
          `  font-family: "${escapeCssString(group.family)}";\n` +
          `  src: url("${urlFor(face.file)}") format("${format}");\n` +
          `  font-weight: ${face.weight};\n` +
          `  font-style: normal;\n` +
          `  font-display: swap;\n` +
          `}`
      );
    }
  }
  if (blocks.length === 0) return "/* RTL Atelier: no bundled fonts found in fonts/ */\n";
  return `/* RTL Atelier: bundled fonts (generated by scripts/fonts.js). Do not edit. */\n${blocks.join("\n\n")}\n`;
}

export function buildFonts(rootDir = ROOT, distDir = join(rootDir, "dist")) {
  const fontsDir = join(rootDir, "fonts");
  let files = [];
  let manifestJson = null;

  if (existsSync(fontsDir)) {
    files = readdirSync(fontsDir).filter((name) => {
      const ext = name.slice(name.lastIndexOf(".")).toLowerCase();
      return Boolean(FONT_EXT_FORMAT[ext]);
    });
    const manifestPath = join(fontsDir, "fonts.json");
    if (existsSync(manifestPath)) {
      try {
        manifestJson = JSON.parse(readFileSync(manifestPath, "utf8"));
      } catch {
        manifestJson = null;
      }
    }
  }

  const families = collectFontFamilies(files, manifestJson);

  mkdirSync(distDir, { recursive: true });

  const pageCss = renderFontFaceCss(families, (file) => `chrome-extension://__MSG_@@extension_id__/${relative(rootDir, join(fontsDir, file)).replace(/\\/g, "/")}`);
  writeFileSync(join(distDir, "fonts.css"), pageCss, "utf8");

  const uiCss = renderFontFaceCss(families, (file) => `../${relative(rootDir, join(fontsDir, file)).replace(/\\/g, "/")}`);
  writeFileSync(join(distDir, "fonts.ui.css"), uiCss, "utf8");

  const manifestOut = {
    families: families.map((group) => group.family),
    weights: Object.fromEntries(families.map((group) => [group.family, group.faces.map((face) => face.weight)])),
    faces: Object.fromEntries(
      families.map((group) => [
        group.family,
        group.faces.map((face) => ({ file: face.file, weight: face.weight })),
      ])
    ),
    generatedAt: new Date().toISOString(),
  };
  writeFileSync(join(distDir, "fonts.manifest.json"), JSON.stringify(manifestOut, null, 2) + "\n", "utf8");

  const coreDir = join(rootDir, "src", "core");
  if (existsSync(coreDir)) {
    const bundledCode = `/* RTL Atelier: bundled fonts static registry (generated by scripts/fonts.js). Do not edit. */
export const BUNDLED_FONTS = ${JSON.stringify(manifestOut.faces, null, 2)};

export function isBundledFont(family) {
  return typeof family === "string" && Boolean(BUNDLED_FONTS[family]);
}

export function bundledFacesForFamily(family) {
  return (typeof family === "string" && BUNDLED_FONTS[family]) || [];
}
`;
    writeFileSync(join(coreDir, "bundled-fonts.js"), bundledCode, "utf8");
  }

  console.log(`fonts: ${families.length} families, ${families.reduce((n, g) => n + g.faces.length, 0)} faces -> dist/fonts.css, dist/fonts.ui.css, dist/fonts.manifest.json`);
  return manifestOut;
}

const invokedDirectly =
  typeof process !== "undefined" &&
  Boolean(process.argv[1]) &&
  fileURLToPath(import.meta.url).toLowerCase() === process.argv[1].toLowerCase();

if (invokedDirectly) {
  buildFonts();
}
